@lru_cache(maxsize=1)
def ths_industries() -> tuple[str, ...]:
    """同花顺行业板块名全集。"""
    return tuple(ds.industry_list()["name"].tolist())


def map_to_ths(boards: list[str]) -> tuple[str | None, str]:
    """把东财板块列表映射为同花顺行业名。返回 (行业名 or None, 命中方式)。"""
    universe = set(ths_industries())
    # 1) 直接命中
    for b in boards:
        if b in universe:
            return b, "直接命中"
    # 2) 别名表
    for b in boards:
        if b in ALIAS and ALIAS[b] in universe:
            return ALIAS[b], "别名表"
    # 3) 东财一级 -> 同花顺细分（取第一个可命中的）
    for b in boards:
        cands = EASTMONEY_MAP.get(b)
        if cands:
            for c in cands:
                if c in universe:
                    return c, f"映射表({b})"
    # 4) 关键词包含匹配
    for b in boards:
        for u in universe:
            if b and (b in u or u in b):
                return u, "模糊匹配"
    return None, "未命中"


@lru_cache(maxsize=1)
def _industry_returns(beg: str = "20251001") -> pd.DataFrame:
    """90 个同花顺行业指数的日收益矩阵（用于相关性兜底，缓存复用）。"""
    cols = {}
    for n in ths_industries():
        try:
            d = ds.industry_index(n, beg)
            if len(d) > 60:
                cols[n] = d["close"].pct_change()
        except Exception:                            # noqa: BLE001
            continue
    return pd.DataFrame(cols).dropna(how="all")


def infer_by_correlation(stock_code: str, top: int = 1) -> tuple[str | None, float]:
    """相关性兜底：个股日收益 vs 各行业指数日收益，取相关性最高的行业。"""
    try:
        s = ds.stock_kline(stock_code)["close"].pct_change()
    except Exception:                                # noqa: BLE001
        return None, np.nan
    R = _industry_returns()
    if R.empty or len(s) < 40:
        return None, np.nan
    common = R.index.intersection(s.index)
    if len(common) < 40:
        return None, np.nan
    corr = R.loc[common].corrwith(s.loc[common]).dropna().sort_values(ascending=False)
    if corr.empty:
        return None, np.nan
    if top == 1:
        return str(corr.index[0]), float(corr.iloc[0])
    return [(str(i), float(v)) for i, v in corr.head(top).items()], float(corr.iloc[0])


def _clean_name(s: str) -> str:
    """去掉 -W / -S / -SW 等港股后缀与空格，便于名称比对。"""
    return str(s).replace(" ", "").replace("　", "").strip()


def _name_match(a: str, b: str) -> bool:
    """宽松名称比对：去后缀后相等，或互为前缀（长度>=3）。"""
    a, b = _clean_name(a), _clean_name(b)
    if not a or not b:
        return False
    if a == b:
        return True
    short, long = (a, b) if len(a) <= len(b) else (b, a)
    return len(short) >= 3 and long.startswith(short)


def resolve(stock_code: str, holding_name: str = "") -> dict:
    """
    综合解析个股 -> 同花顺行业。

    关键：天天基金的持仓代码会把港股补零成 6 位（腾讯 00700 -> 000700），
    直接用会命中不相干的 A 股。因此必须用「F10 返回的公司名」与「持仓名称」比对，
    不一致则说明代码口径错配，改走名称搜索 / 港股映射表。
    """
    prof = ds.stock_profile(stock_code)
    boards = prof["boards"]
    # --- 1) 代码口径一致：F10 公司名与持仓名吻合 ---
    if boards and (not holding_name or _name_match(prof["name"], holding_name)):
        name, how = map_to_ths(boards)
        if name:
            return {"code": stock_code, "industry": name, "source": how,
                    "boards": boards, "corr": None, "matched_name": prof["name"]}
    # --- 2) 代码错配（多为港股）：按名称搜索 A 股对应标的 ---
    if holding_name:
        for cand in ds.search_stock(holding_name):
            if not _name_match(cand["name"], holding_name):
                continue
            p2 = ds.stock_profile(cand["code"])
            if not p2["boards"] or not _name_match(p2["name"], cand["name"]):
                continue
            name, how = map_to_ths(p2["boards"])
            if name:
                return {"code": cand["code"], "industry": name,
                        "source": f"{how}·按名搜索({cand['market']})",
                        "boards": p2["boards"], "corr": None,
                        "matched_name": p2["name"], "原代码": stock_code}
    # --- 3) 港股 / 中概映射表 ---
    if holding_name:
        key = _clean_name(holding_name)
        if key in HK_MAP:
            return {"code": stock_code, "industry": HK_MAP[key], "source": "港股映射表",
                    "boards": [], "corr": None, "matched_name": holding_name}
        for k, v in HK_MAP.items():
            if _name_match(k, key):
                return {"code": stock_code, "industry": v, "source": "港股映射表",
                        "boards": [], "corr": None, "matched_name": holding_name}
    # --- 4) 相关性兜底（仅在代码确实是 A 股时才有意义） ---
    if boards:
        name, how = map_to_ths(boards)
        if name:
            return {"code": stock_code, "industry": name, "source": how + "·名称未校验",
                    "boards": boards, "corr": None, "matched_name": prof["name"],
                    "warn": "F10名称与持仓名不一致，行业可能不准"}
    name, corr = infer_by_correlation(stock_code)
    return {"code": stock_code, "industry": name,
            "source": f"相关性推断({corr:.2f})" if name else "未识别",
            "boards": boards, "corr": round(corr, 3) if corr == corr else None,
            "matched_name": prof["name"]}


